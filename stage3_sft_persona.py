def main():
    p = argparse.ArgumentParser()
    p.add_argument("--output", type=Path, default=Path("data_stage3_sft/seed_identity.jsonl"))
    args = p.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.exists():
        p.error(f"Refusing to overwrite: {args.output}")
    with args.output.open("w", encoding="utf-8") as file:
        for question, answer, category in EXAMPLES:
            row = {
                "category": category,
                "origin": "NULLXES hand-authored style seed",
                "messages": [
                    {"role": "system", "content": SVAROG_SYSTEM},
                    {"role": "user", "content": question},
                    {"role": "assistant", "content": answer},
                ],
            }
            file.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"SVAROG SFT persona seed: {len(EXAMPLES)} examples -> {args.output}")
    print("Seed only. Do NOT train on this alone or mix it into pretraining.")


if __name__ == "__main__":
    main()
